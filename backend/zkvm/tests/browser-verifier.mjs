import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { performance } from 'node:perf_hooks';
import { createHash } from 'node:crypto';
import { initSync, verify_replay, replay_info, public_replay } from '../../../frontend/dist/replay/huma_replay_browser.js';
const root = new URL('../../../', import.meta.url);
const wasm = initSync({ module: await readFile(new URL('frontend/dist/replay/huma_replay_browser_bg.wasm', root)) });
assert.throws(() => wasm.memory.grow(2048), RangeError); // Module ceiling is 128 MB.
const source = await readFile(new URL('backend/zkvm/verifier/tests/fixtures/timed-receipt.json', root), 'utf8');
const record = JSON.parse(source);
const witness = JSON.parse(await readFile(new URL('backend/zkvm/common/tests/fixtures/swift-timed.json', root)));
const started = performance.now();
const report = JSON.parse(verify_replay(source, undefined, undefined));
assert.equal(report.verified, true);
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const identity = hash(`huma-replay-identity-v1\n${record.bundle.imageId}\n${hash(Buffer.from(record.bundle.receipt.journal.bytes))}`);
assert.equal(report.proofIdentity, identity);
assert.equal(JSON.parse(verify_replay(JSON.stringify(record, null, 2), undefined, undefined)).proofIdentity, identity);
assert.equal(JSON.parse(verify_replay(public_replay(source), undefined, undefined)).proofIdentity, identity);
assert.equal(report.reportedTime.elapsedMilliseconds, '15');
assert.equal(JSON.parse(replay_info()).verificationOnly, true);
assert.deepEqual(JSON.parse(public_replay(source)), record);
const pin = report.journal.captureKeyHash;
assert.equal(JSON.parse(verify_replay(source, record.text + ' \t', pin)).checks.expectedKey, true);
assert.throws(() => verify_replay(source, record.text + '!', undefined));
assert.throws(() => verify_replay(source, undefined, '0'.repeat(64)));
const selfDeclared = JSON.stringify({ ...record, expectedCaptureKeyHash: '0'.repeat(64) });
assert.equal(JSON.parse(verify_replay(selfDeclared, undefined, undefined)).checks.expectedKey, null);
const revealed = { ...record, capturePublicKey: { format: 'p256-x963-base64', value: witness.session.signedCheckpoints[0].publicKey }, session: witness.session };
const complete = JSON.parse(verify_replay(JSON.stringify(revealed), undefined, pin));
assert.equal(complete.checks.revealedKey, true); assert.equal(complete.checks.revealedHistory, true);
assert.equal(JSON.parse(verify_replay(JSON.stringify(revealed), record.text + ' \t', pin)).checks.revealedHistory, true);
const changed = structuredClone(revealed); changed.session.events[0].insertedText += '!';
assert.throws(() => verify_replay(JSON.stringify(changed), undefined, undefined));
const badKey = structuredClone(revealed); badKey.capturePublicKey.value = witness.session.signedCheckpoints[0].signature;
assert.throws(() => verify_replay(JSON.stringify(badKey), undefined, undefined));
const wrongImage = structuredClone(record); wrongImage.bundle.imageId = '0'.repeat(64);
assert.throws(() => verify_replay(JSON.stringify(wrongImage), undefined, undefined));
const modified = structuredClone(record); modified.bundle.receipt.journal.bytes[0] ^= 1;
assert.throws(() => verify_replay(JSON.stringify(modified), undefined, undefined));
const fake = structuredClone(record); fake.bundle.receipt.inner = { Fake: { claim: fake.bundle.receipt.inner.Succinct.claim } };
assert.throws(() => verify_replay(JSON.stringify(fake), undefined, undefined));
await writeFile(new URL('build/Huma-revealed-replay.json', root), JSON.stringify(revealed));
await writeFile(new URL('build/Huma-browser-report.json', root), JSON.stringify(complete));
console.log(`PASS: WASM receipt, text/key/history/pin/fake tampering, trailing policy and file-supplied-key isolation (${Math.round(performance.now()-started)} ms)`);
